            $this->area($area[0], $area[1], $area[2], $area[3]);
        }
    }

    private function area(int $id, int $cityId, string $title, string $postCode): void {
        $area = new CityArea();

        $area->id = $id;
        $area->city_id = $cityId;
        $area->title = $title;
        $area->post_code = $postCode;
        $area->ranking = $id;

        $area->save();
    }

    private function city(int $id, string $title, int $ranking): void {
        $city = new City();

        $city->id = $id;
        $city->title = $title;
        $city->ranking = $ranking;

        $city->save();
    }

