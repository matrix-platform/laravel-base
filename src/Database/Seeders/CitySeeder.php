    public function run(): void {
        foreach (self::CITIES as $city) {
            $this->city($city[0], $city[1], $city[2], $city[3], $city[4], $city[5]);
        }

        foreach (self::AREAS as $area) {
            $this->area($area[0], $area[1], $area[2], $area[3], $area[4], $area[5], $area[6]);
        }
    }

    private function area(int $id, int $cityId, string $title, ?string $titleEn, string $titleCn, string $titleJp, string $postCode): void {
        $area = new CityArea();

        $area->id = $id;
        $area->city_id = $cityId;
        $area->post_code = $postCode;
        $area->ranking = $id;

        $this->titles($area, $title, $titleEn, $titleCn, $titleJp);

        $area->save();
    }

    private function city(int $id, string $title, ?string $titleEn, string $titleCn, string $titleJp, int $ranking): void {
        $city = new City();

        $city->id = $id;
        $city->ranking = $ranking;

        $this->titles($city, $title, $titleEn, $titleCn, $titleJp);

        $city->save();
    }

    private function titles(Model $model, string $tw, ?string $en, string $cn, string $jp): void {
        foreach (['tw' => $tw, 'en' => $en, 'cn' => $cn, 'jp' => $jp] as $locale => $value) {
            if (in_array($locale, locales(), true)) {
                $model->setAttribute("title__{$locale}", $value);
            }
        }
    }

