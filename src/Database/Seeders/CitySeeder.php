        }
    }

    private function area(int $id, int $cityId, string $title, ?string $titleEn, string $postCode): void {
        $area = new CityArea();

        $area->id = $id;
        $area->city_id = $cityId;
        $area->title__tw = $title;
        $area->title__en = $titleEn;
        $area->post_code = $postCode;
        $area->ranking = $id;

        $area->save();
    }

